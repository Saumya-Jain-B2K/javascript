// primitive datatypes in js
// string
var name1 = 'Saumya Jain';
console.log('My name is ' + name1);

//using typeof operator
console.log(typeof name1);

//numbers
let marks = 34;
console.log(typeof marks);

//boolean
let bool = true;
console.log(typeof bool);

//null
let isNull = null;
console.log(typeof isNull);

//undefined
let undef = undefined;
console.log(typeof undef);

//reference datatypes

//arrays
let arr = [1,2,4,'saumya', true];
console.log(typeof arr);
console.log(arr)
console.log(arr[2]);

//object literals
let obj = {
    saumya : 79,
    ruchit : 50,
    rashi : 45
};
console.log(obj);
console.log(typeof obj);
